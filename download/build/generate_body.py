def h1_block(number, title):
    """H1 heading + accent underline rule."""
    return [
        Paragraph('<b>' + str(number) + '   ' + title + '</b>', h1_style),
        HRFlowable(width='100%', thickness=1.2, color=ACCENT,
                   spaceBefore=3, spaceAfter=10),
    ]


def callout(text):
    """Accent left border + light tint background (CalloutBox pattern)."""
    inner = Paragraph(text, callout_style)
    t = Table([[inner]], colWidths=[AVAIL * 0.96], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('LINEBEFORE', (0, 0), (0, -1), 3, ACCENT),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 12),
        ('TOPPADDING', (0, 0), (-1, -1), 7),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    return t


def styled_table(data, col_ratios, repeat_header=True):
    """Standard palette table: header fill + stripes + grid, centered."""
    col_widths = [r * AVAIL for r in col_ratios]
    assert abs(sum(col_ratios) - 1.0) < 0.001
    assert sum(col_widths) <= AVAIL + 0.5, 'table wider than available width'
    t = Table(data, colWidths=col_widths, hAlign='CENTER',
              repeatRows=1 if repeat_header else 0)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [TABLE_ROW_EVEN, TABLE_ROW_ODD]),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]))
    return t


