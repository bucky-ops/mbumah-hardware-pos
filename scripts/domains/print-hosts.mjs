#!/usr/bin/env node
// MBUMAH HARDWARE POS - Print hosts-file entries for local subdomain workspaces
//
// Usage:
//   node scripts/domains/print-hosts.mjs                  # 127.0.0.1 + :3000 hosts block
//   node scripts/domains/print-hosts.mjs --ip 192.168.1.20  # LAN mode (one LAN server)
//   node scripts/domains/print-hosts.mjs --domain mbumah.lan
//   node scripts/domains/print-hosts.mjs --ipv6           # include ::1 entries
//
// The script ONLY PRINTS copy-pasteable entries; it never modifies the system
// hosts file. Apply them yourself:
//   macOS / Linux:  sudo nano /etc/hosts          (then paste)
//   Windows:        run Notepad as Administrator, open C:\Windows\System32\drivers\etc\hosts
//
// Store slugs/subdomains come from scripts/domains/stores.config.json, which
// mirrors prisma/seed.ts and src/lib/store-info.ts.

import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const configPath = join(scriptDir, 'stores.config.json');

function parseArgs(argv) {
  const args = { ip: '127.0.0.1', domain: null, ipv6: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--ip' && argv[i + 1]) { args.ip = argv[i + 1]; i++; }
    else if (a === '--domain' && argv[i + 1]) { args.domain = argv[i + 1]; i++; }
    else if (a === '--ipv6') { args.ipv6 = true; }
    else if (a === '--help' || a === '-h') { args.help = true; }
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log('Usage: node scripts/domains/print-hosts.mjs [--ip 127.0.0.1] [--domain mbumah.test] [--ipv6]');
    process.exit(0);
  }

  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const rootDomain = args.domain || config.rootDomainLocal || 'mbumah.test';
  const ip = args.ip;
  const port = config.defaultPort || 3000;

  const hosts = [rootDomain, ...config.stores.map((s) => s.subdomain)];
  const lines = [];
  lines.push('# MBUMAH HARDWARE POS - branch workspace hosts entries (v2.16.0)');
  lines.push(`# Generated by scripts/domains/print-hosts.mjs at ${new Date().toISOString()}`);
  lines.push(`# Root domain: ${rootDomain} | Server IP: ${ip} | App port: ${port}`);
  lines.push('# Paste into your hosts file (see docs/local-offline-setup.md).');
  lines.push('');
  for (const host of hosts) {
    lines.push(`${ip}\t${host}`);
  }
  if (args.ipv6) {
    lines.push('');
    lines.push('# Optional IPv6 entries');
    for (const host of hosts) {
      lines.push(`::1\t${host}`);
    }
  }
  lines.push('');
  lines.push(`# Root console:    http://${rootDomain}:${port}`);
  lines.push(`# Branch example:  http://${config.stores[0].subdomain}.${rootDomain}:${port}`);
  lines.push(`# Path fallback:   http://${ip}:${port}/stores/${config.stores[0].slug}/dashboard`);
  console.log(lines.join('\n'));
}

main();
